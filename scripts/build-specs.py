#!/usr/bin/env python3
"""Build the document spec snippets from the data files in scripts/specs/.

Each scripts/specs/<cc>/<doc>.json is the source of truth for one document spec.
This script writes, for each country:

  snippets/specs/<cc>/<doc>.mdx     export const <name> = {...} plus Markdown tables
  snippets/specs/<cc>/errors.mdx    every GOBL validation rule, with the fix
  snippets/specs/<cc>/index.mdx     every government field, with its row ID

The Markdown tables are for the `.md` export that agents read. The exported
constant feeds <SpecExplorer /> (snippets/components/spec-explorer.jsx).

Never edit the files in snippets/specs/ by hand. Edit the JSON and run:

    python3 scripts/build-specs.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "scripts" / "specs"
OUT = ROOT / "snippets" / "specs"

PAGES = {
    "parties": "/guides/mx-cfdi-parties",
    "invoice": "/guides/mx-cfdi-invoice",
    "credit-note": "/guides/mx-cfdi-credit-note",
    "payment": "/guides/mx-cfdi-payment",
    "global": "/guides/mx-cfdi-global",
}
ORDER = ["parties", "invoice", "credit-note", "payment", "global"]
HEADER = "{/* Generated by scripts/build-specs.py. Do not edit. */}\n\n"


def code(text):
    """Format a comma-separated list of field names as inline code."""
    if not text:
        return ""
    return ", ".join("`" + part.strip() + "`" for part in text.split(", "))


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


LEVEL = {"M": "Mandatory", "C": "Conditional", "O": "Optional", "No": "Not supported"}


def level(row):
    return LEVEL["No"] if row["send"] == "No" else LEVEL[row["req"]]


def is_auto(row):
    return row.get("auto", row["send"] == "Auto")


def notes(row):
    parts = []
    if row.get("when"):
        parts.append("When " + row["when"] + ".")
    if row.get("default"):
        parts.append("Default: " + row["default"].rstrip(".") + ".")
    if row.get("values"):
        parts.append("Values: " + row["values"])
    if row.get("rule"):
        parts.append(row["rule"])
    if row.get("link"):
        parts.append("[" + row["link"]["label"] + "](" + row["link"]["url"] + ").")
    if row.get("errors"):
        parts.append("Rule " + ", ".join("`" + n + "`" for n in row["errors"]) + ".")
    return " ".join(parts)


def tables(spec):
    out = []
    for sec in spec["sections"]:
        out.append("**" + sec["title"] + "** (`" + sec["node"] + "`)\n")
        if sec.get("intro"):
            out.append(sec["intro"] + "\n")
        out.append("| ID | CFDI field | GOBL field | Level | Auto-filled | Format | Notes | Example |")
        out.append("|---|---|---|---|:---:|---|---|---|")
        for r in sec["rows"]:
            example = "`" + r["example"] + "`" if r.get("example") else ""
            out.append(
                "| `{id}` | {cfdi} | {gobl} | {level} | {auto} | {fmt} | {notes} | {ex} |".format(
                    id=r["id"],
                    cfdi=code(r["cfdi"]),
                    gobl=code(r["gobl"]),
                    level=level(r),
                    auto=("Always" if r["send"] == "Auto" else "If empty") if is_auto(r) else "",
                    fmt=cell(r["format"]),
                    notes=cell(notes(r)),
                    ex=example,
                )
            )
        out.append("")
    return "\n".join(out)


def build_country(cc):
    src = SRC / cc
    out = OUT / cc
    out.mkdir(parents=True, exist_ok=True)
    specs = {}
    for path in sorted(src.glob("*.json")):
        spec = json.loads(path.read_text())
        specs[spec["key"]] = spec
        body = (
            HEADER
            + "export const "
            + spec["export"]
            + " = "
            + json.dumps(spec, ensure_ascii=False, indent=2)
            + ";\n\n"
            + tables(spec)
        )
        (out / (spec["key"] + ".mdx")).write_text(body)

    keys = [k for k in ORDER if k in specs] + [k for k in specs if k not in ORDER]

    # Error lookup
    lines = [HEADER, "| Error code | GOBL message | What to do | Spec row |", "|---|---|---|---|"]
    count = 0
    for key in keys:
        spec = specs[key]
        for rule in spec.get("rules", []):
            rows = ", ".join("`" + r + "`" for r in rule["rows"])
            lines.append(
                "| `{code}` | {msg} | {fix} | {rows} |".format(
                    code=spec["errorPrefix"] + rule["n"],
                    msg=cell(rule["msg"]),
                    fix=cell(rule["fix"]),
                    rows=rows,
                )
            )
            count += 1
    (out / "errors.mdx").write_text("\n".join(lines) + "\n")

    # Field index
    lines = [HEADER, "| CFDI field | ID | GOBL field | Level | Spec |", "|---|---|---|---|---|"]
    rows = 0
    for key in keys:
        spec = specs[key]
        page = PAGES.get(key, "")
        for sec in spec["sections"]:
            node = sec["node"].split(" and ")[0]
            for r in sec["rows"]:
                first = r["cfdi"].split(", ")[0]
                sep = "" if first.startswith("@") else "/"
                lines.append(
                    "| `{field}` | `{id}` | {gobl} | {send} | [{title}]({page}) |".format(
                        field=node + sep + first if len(r["cfdi"].split(", ")) == 1 else node + " " + r["cfdi"],
                        id=r["id"],
                        gobl=code(r["gobl"]),
                        send=level(r),
                        title=spec["title"],
                        page=page,
                    )
                )
                rows += 1
    (out / "index.mdx").write_text("\n".join(lines) + "\n")
    print(f"{cc}: {len(specs)} specs, {rows} rows, {count} rules")


def main():
    countries = sys.argv[1:] or [p.name for p in sorted(SRC.iterdir()) if p.is_dir()]
    for cc in countries:
        build_country(cc)


if __name__ == "__main__":
    main()
